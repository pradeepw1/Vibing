// Builds src/land.js: the world's coastlines as [lon, lat] rings, used to paint
// the Earth texture in the browser. Data: Natural Earth (public domain), via the
// world-atlas package.
//
//   node tools/make-land.mjs [110m|50m]
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const res = process.argv[2] ?? "50m";
const TOLERANCE = 0.12; // degrees; simplify lines to within this
const MIN_AREA = 0.3; // square degrees; smaller islands and lakes are skipped

const topo = JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/land-${res}.json`, import.meta.url)));
const land = feature(topo, topo.objects.land);

const rings = [];
for (const f of land.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      const pts = simplify(unwrap(ring));
      // A ring that goes all the way round (Antarctica) is closed off along the pole.
      const turn = pts[pts.length - 1][0] - pts[0][0];
      if (Math.abs(turn) > 300) {
        const pole = pts.reduce((s, p) => s + p[1], 0) < 0 ? -90 : 90;
        pts.push([pts[pts.length - 1][0], pole], [pts[0][0], pole]);
      }
      const out = pts.flatMap(([lon, lat]) => [+lon.toFixed(2), +lat.toFixed(2)]);
      if (out.length >= 8 && Math.abs(area(out)) >= MIN_AREA) rings.push(out);
    }
  }
}

// Rings that cross the 180 degree line jump from +180 to -180. Make the
// longitudes continuous instead (they may then run past 180); the painter
// draws every ring three times, shifted by a full turn, to cover the seam.
function unwrap(ring) {
  const out = [ring[0].slice()];
  for (let i = 1; i < ring.length; i++) {
    let lon = ring[i][0];
    const prev = out[i - 1][0];
    while (lon - prev > 180) lon -= 360;
    while (lon - prev < -180) lon += 360;
    out.push([lon, ring[i][1]]);
  }
  return out;
}

// Ramer-Douglas-Peucker line simplification.
function simplify(pts) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay);
    let worst = 0, at = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      // A closed ring starts and ends on the same point, so fall back to plain distance.
      const d = len < 1e-9
        ? Math.hypot(px - ax, py - ay)
        : Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / len;
      if (d > worst) { worst = d; at = i; }
    }
    if (worst > TOLERANCE) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

function area(flat) {
  let a = 0;
  for (let i = 0; i < flat.length; i += 2) {
    const j = (i + 2) % flat.length;
    a += flat[i] * flat[j + 1] - flat[j] * flat[i + 1];
  }
  return a / 2;
}

const body = rings.map((r) => "[" + r.join(",") + "]").join(",\n");
writeFileSync(
  new URL("../src/land.js", import.meta.url),
  `// Generated by tools/make-land.mjs from Natural Earth ${res} land (public domain).\n` +
    `// Each ring is a flat list: lon, lat, lon, lat, ... Longitudes can run past +-180.\n` +
    `export const LAND = [\n${body}\n];\n`,
);
console.log(`${rings.length} rings, ${rings.reduce((n, r) => n + r.length / 2, 0)} points`);
